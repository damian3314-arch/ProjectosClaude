-- 0090 · Lo que entró, según el mostrador
--
-- Hasta hoy la tesorería sacaba el ingreso de la Caja, y la Caja no
-- empezó a registrar hasta el 10 de agosto. Por eso agosto salía con
-- 9.815.000 de entradas y una pérdida de 2.171.900: le faltaban los
-- primeros nueve días del mes.
--
-- Damián mandó el reporte de ventas de AdminGym, que es el sistema del
-- mostrador donde cada venta se factura. Va desde enero y trae 4.162
-- ventas por 125.284.500. Ese es el ingreso de verdad.
--
-- ── POR QUÉ AGREGADO Y SIN NOMBRES ──────────────────────────────────
--
-- Se guarda por día × tipo de membresía × medio de pago: 1.029 renglones
-- en vez de 4.162. Es el grano que la tesorería necesita —cuánto entró,
-- de qué y por dónde— y evita meter otra copia de nombres, cédulas,
-- correos y celulares en la base. Esa data ya vive en su sitio y con sus
-- permisos; duplicarla aquí sería cargar un riesgo a cambio de nada.
--
-- ── QUÉ SE CUENTA COMO COBRADO ──────────────────────────────────────
--
-- El reporte trae dos columnas, «Valor» y «Valor a Pagar», y en 8 de las
-- 4.162 ventas no coinciden: son descuentos y pagos parciales, y las dos
-- columnas no se usan igual en los dos casos. Se toma la menor de las
-- dos, que es la única lectura que da un número sensato en los ocho.
-- `ajustadas_n` cuenta cuántas de esas hay en cada renglón para poder
-- encontrarlas. En total mueven 75.000 pesos sobre 125 millones.
--
-- Para recargar con un export más nuevo: pruebas/cargar-ventas.py lo
-- vuelve a generar desde el .xlsx, y el `on conflict` pisa lo viejo.

create table if not exists ventas_mostrador (
  id          uuid primary key default extensions.gen_random_uuid(),
  dia         date not null,
  -- Tal como lo nombra AdminGym: 'CLASE SUELTA', 'PLAN MENSUALIDAD 6:00PM'…
  membresia   text not null,
  medio       text not null,          -- BANCOLOMBIA | EFECTIVO | NEQUI
  cobrado_cop bigint not null,
  ventas_n    int not null,
  -- Ventas del renglón donde «Valor» y «Valor a Pagar» no coincidían.
  ajustadas_n int not null default 0,
  cargado_at  timestamptz not null default now(),
  constraint ventas_mostrador_cobrado_ck check (cobrado_cop >= 0),
  constraint ventas_mostrador_n_ck check (ventas_n > 0)
);

-- Recargar el mismo export no duplica: pisa el renglón.
create unique index if not exists ventas_mostrador_llave
  on ventas_mostrador (dia, membresia, medio);
create index if not exists ventas_mostrador_dia on ventas_mostrador (dia);

alter table ventas_mostrador enable row level security;
revoke all on table ventas_mostrador from public, anon, authenticated;

